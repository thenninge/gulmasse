const DICTS: Record<Lang, Dict> = { no, en, ja };
export const LOCALE: Record<Lang, string> = { no: 'nb-NO', en: 'en-GB', ja: 'ja-JP' };

export function translate(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const template = DICTS[lang][key] ?? DICTS.no[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, p) => (p in params ? String(params[p]) : ''));
}

/** Number with fixed decimals: decimal comma in Norwegian, point otherwise. */
export function formatNumber(lang: Lang, n: number | null | undefined, decimals = 1): string {
  if (n == null || !Number.isFinite(n)) return '—';
  const s = n.toFixed(decimals);
  return lang === 'no' ? s.replace('.', ',') : s;
}

export function isLang(v: unknown): v is Lang {
  return v === 'no' || v === 'en' || v === 'ja';
}
